//! Screen manifest generation for HERDR agent detection.
//!
//! Screen manifests tell HERDR how to detect agent state from terminal
//! output. These TOML files define rules that match text patterns in
//! the pane's bottom buffer.
//!
//! HERDR evaluates manifests against the live bottom-buffer snapshot.
//! Each rule has a `state` (working/idle/blocked), match patterns,
//! and optional region constraints.

/// A single detection rule in a screen manifest.
pub struct DetectionRule {
    /// Agent state this rule asserts.
    pub state: AgentState,
    /// Text patterns that must all match (AND logic).
    pub patterns: Vec<String>,
    /// Optional description for documentation.
    pub description: String,
}

/// Screen manifest for an agent. Generates the TOML that HERDR
/// uses for screen-based detection.
pub struct ScreenManifest {
    /// Agent name (e.g. "jcode", "forgecode").
    pub agent: String,
    /// Manifest version.
    pub version: String,
    /// Detection rules evaluated in order.
    pub rules: Vec<DetectionRule>,
}

impl ScreenManifest {
    /// Generate the TOML manifest string.
    pub fn to_toml(&self) -> String {
        let mut out = format!(
            "# HERDR screen manifest for {}\n\
             # Auto-generated by jcode-herdr\n\
             agent = \"{}\"\n\
             version = \"{}\"\n\n",
            self.agent, self.agent, self.version
        );

        for (i, rule) in self.rules.iter().enumerate() {
            out.push_str(&format!(
                "[[rules]]\n\
                 # Rule {}: {}\n\
                 state = \"{}\"\n",
                i + 1,
                rule.description,
                rule.state.as_str(),
            ));
            // Use TOML inline array to avoid duplicate keys
            out.push_str("patterns = [");
            for (j, pattern) in rule.patterns.iter().enumerate() {
                if j > 0 {
                    out.push_str(", ");
                }
                out.push_str(&format!("{:?}", pattern));
            }
            out.push_str("]\n\n");
        }

        out
    }
}

use crate::state::AgentState;

/// Build the jcode screen manifest.
pub fn jcode_manifest() -> ScreenManifest {
    ScreenManifest {
        agent: "jcode".to_string(),
        version: "1".to_string(),
        rules: vec![
            DetectionRule {
                state: AgentState::Working,
                patterns: vec!["●".to_string()],
                description: "jcode spinner active (working)".to_string(),
            },
            DetectionRule {
                state: AgentState::Working,
                patterns: vec!["Thinking...".to_string()],
                description: "jcode thinking state".to_string(),
            },
            DetectionRule {
                state: AgentState::Working,
                patterns: vec!["Baking...".to_string()],
                description: "jcode baking state (processing)".to_string(),
            },
            DetectionRule {
                state: AgentState::Working,
                patterns: vec!["Streaming...".to_string()],
                description: "jcode streaming response".to_string(),
            },
            DetectionRule {
                state: AgentState::Blocked,
                patterns: vec!["❯".to_string(), "Yes".to_string(), "No".to_string()],
                description: "jcode permission prompt".to_string(),
            },
            DetectionRule {
                state: AgentState::Blocked,
                patterns: vec!["Do you want to proceed?".to_string()],
                description: "jcode confirmation prompt".to_string(),
            },
            DetectionRule {
                state: AgentState::Idle,
                patterns: vec!["❯".to_string()],
                description: "jcode input prompt (idle)".to_string(),
            },
        ],
    }
}

